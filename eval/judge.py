r"""
LLM judge for AskPG generation runs. Judges the saved answers of eval\results\gen-<name>.json; never calls the
generator and never re-runs retrieval, so the answers stay frozen.

Usage (from the repo root, cmd):
    python eval\judge.py g1 --ids amb-04 multi-04 fact-10      # smoke test + validation against my manual reads
    python eval\judge.py g1                                     # all status=ok answers (2 calls each)
    python eval\judge.py g1 --resume                            # redo only judge errors / missing questions

Judge model: JUDGE_MODEL in .env or the environment (default nvidia/nemotron-3-super-120b-a12b). Use a model
that is NOT the generator (g1 was generated by openai/gpt-oss-20b) to limit self-preference. Same endpoint and key
as the generator (LLM_BASE_URL, LLM_API_KEY); JUDGE_MAX_TOKENS (default 4000) because reasoning models think first.

Two calls per answer
  1. FAITHFULNESS, per claim. The judge lists every factual claim in the answer, with the source numbers the answer
     cites for it, and judges each claim ONLY against the numbered sources the generator was shown (rebuilt from
     chunks.jsonl):  supported | not_supported | contradicted.  A claim with citations is judged against the cited
     sources; `found_in_other_source` records when only an uncited shown source supports it (attribution error).
  2. CORRECTNESS and COMPLETENESS against reference_answer from the dataset (the judge does not see the sources):
     correct|partial|incorrect and complete|partial|missing. Completeness is strict for ALL types: for an ambiguous
     question the reference lists alternatives, so "partial" there can be fine; read it by type.

Outputs: eval\results\gen-<name>_judge.json (meta with judge model, date, prompt hash, chunks md5; per-question
claims and verdicts; summary). Refused answers are not judged (refusal behaviour is already scored by run_gen_eval).

What this is NOT: a ground truth. It is one LLM's reading, with its own errors. Before trusting a number, read the
printed contradicted / not_supported claims, and check the validation block (3 answers I read by hand, so it is a
smoke test of the judge, not an agreement statistic). Untested against the real API when written.
"""
import argparse
import hashlib
import json
import os
import re
import sys
import time
from collections import Counter
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import run_eval as ev  # noqa: E402  (also puts <repo>/src on sys.path)
import generate as gen  # noqa: E402  (loads .env)

JUDGE_MODEL = os.environ.get("JUDGE_MODEL") or "nvidia/nemotron-3-super-120b-a12b"
JUDGE_MAX_TOKENS = int(os.environ.get("JUDGE_MAX_TOKENS") or 4000)

VERDICTS = ("supported", "not_supported", "contradicted")
CORRECT = ("correct", "partial", "incorrect")
COMPLETE = ("complete", "partial", "missing")

# Claim-level checks from answers I read by hand against the doc text (read_g1.txt). (id, lowercase substring of the
# claim, should the judge flag it as not_supported or contradicted?). "contradicted" vs "not_supported" is NOT used
# here: for amb-04 the secure-view form sits in a chunk the generator never saw, and for multi-04 the speed/size claims
# come from a passage about standalone hot backups, so both labels are defensible. The check is only: flagged or not.
KNOWN_CLAIMS = [
    ("amb-04", "security barrier", True),        # invalid CREATE VIEW syntax, cited to the insecure example
    ("amb-04", "app_user", True),                # invented example under a citation
    ("amb-04", "grant select on phone_number", False),   # verbatim in rules-privileges:0001/0002
    ("multi-04", "larger", True),                # from a passage about standalone hot backups
    ("multi-04", "faster", True),
    ("fact-10", "5min", True),                   # invented snippet (source only says "milliseconds if no units")
    ("fact-10", "log_min_error_statement", False),   # stated in runtime-config-client:0008
]

FAITH_SYSTEM = """You are a strict fact-checking judge. You get numbered SOURCES, a QUESTION and an ANSWER written by another model.
List every factual claim in the ANSWER (one per sentence or bullet; code snippets and examples count as claims; skip
pure formatting). For each claim record the source numbers the ANSWER cites for it (empty list if none) and judge it
ONLY against the SOURCES, never with outside knowledge, even if the claim is true:
- "supported": the cited sources state it or directly imply it (if no source is cited: any source does).
- "not_supported": the cited sources do not state it.
- "contradicted": a source states the opposite, or the claim uses a source's example in a way the source says is wrong.
Set "found_in_other_source" to true only if the claim is supported by a shown source that the ANSWER did not cite.
"evidence": a quote of fewer than 15 words from the deciding source, or "".
Reply with ONLY this JSON, no other text:
{"claims":[{"claim":"...","cited":[1],"verdict":"supported|not_supported|contradicted","found_in_other_source":false,"evidence":"..."}]}"""

CORR_SYSTEM = """You compare an ANSWER with a REFERENCE answer for a QUESTION. Use no outside knowledge.
"correctness": "correct" = nothing in the ANSWER conflicts with the REFERENCE and its main point matches; "partial" = some
of it matches or something minor conflicts; "incorrect" = the main point is wrong or conflicts.
"completeness": "complete" = covers every key point of the REFERENCE; "partial" = covers some; "missing" = covers none.
Reply with ONLY this JSON, no other text:
{"correctness":"correct|partial|incorrect","completeness":"complete|partial|missing","missing_points":["..."],"conflicts":["..."]}"""

PROMPT_MD5 = hashlib.md5((FAITH_SYSTEM + CORR_SYSTEM).encode("utf-8")).hexdigest()[:12]


# --------------------------------------------------------------------------- LLM plumbing
def make_judge_llm():
    from openai import OpenAI

    client = OpenAI(base_url=gen.LLM_BASE_URL, api_key=gen.LLM_API_KEY, timeout=180, max_retries=2)
    last = [0.0]

    def call(messages):
        wait = gen.MIN_GAP_S - (time.perf_counter() - last[0])
        if wait > 0:
            time.sleep(wait)
        last[0] = time.perf_counter()
        t0 = time.perf_counter()
        r = client.chat.completions.create(model=JUDGE_MODEL, messages=messages, temperature=0,
                                           max_tokens=JUDGE_MAX_TOKENS)
        ms = (time.perf_counter() - t0) * 1000
        text = gen.strip_think(r.choices[0].message.content or "")
        if not text:
            raise RuntimeError(f"Empty judge answer from {JUDGE_MODEL} (finish_reason={r.choices[0].finish_reason}); "
                               f"raise JUDGE_MAX_TOKENS")
        u = r.usage
        return text, {"prompt_tokens": getattr(u, "prompt_tokens", 0) or 0,
                      "completion_tokens": getattr(u, "completion_tokens", 0) or 0, "llm_ms": ms}

    return call


def parse_json(text: str):
    t = re.sub(r"^```(?:json)?\s*|\s*```$", "", text.strip())
    i, j = t.find("{"), t.rfind("}")
    if i < 0 or j <= i:
        return None
    try:
        obj = json.loads(t[i:j + 1])
    except json.JSONDecodeError:
        return None
    return obj if isinstance(obj, dict) else None


def ask_json(llm, system: str, user: str, retries: int = 1):
    """-> (obj or None, usage, error). One corrective retry when the reply is not valid JSON."""
    messages = [{"role": "system", "content": system}, {"role": "user", "content": user}]
    usage = {"prompt_tokens": 0, "completion_tokens": 0, "llm_ms": 0.0}
    for attempt in range(retries + 1):
        try:
            text, u = llm(messages)
        except Exception as e:  # timeout, 404, 429, empty reasoning answer
            return None, usage, f"{type(e).__name__}: {e}"
        for k in usage:
            usage[k] += u[k]
        obj = parse_json(text)
        if obj is not None:
            return obj, usage, None
        messages = messages + [{"role": "assistant", "content": text},
                               {"role": "user", "content": "That was not valid JSON. Reply with ONLY the JSON object."}]
    return None, usage, "JSONError: judge reply was not valid JSON after a retry"


# --------------------------------------------------------------------------- judging one answer
def norm_claims(obj: dict) -> list[dict]:
    out = []
    for c in obj.get("claims", []) if obj else []:
        if not isinstance(c, dict) or not c.get("claim"):
            continue
        v = str(c.get("verdict", "")).strip().lower()
        cited = [n for n in c.get("cited", []) if isinstance(n, int)] if isinstance(c.get("cited"), list) else []
        out.append({"claim": str(c["claim"]), "cited": cited, "verdict": v if v in VERDICTS else "invalid",
                    "found_in_other_source": bool(c.get("found_in_other_source")),
                    "evidence": str(c.get("evidence", ""))[:200]})
    return out


def judge_question(q: dict, answer_rec: dict, shown: list[dict], reference: str, llm, closed_book: bool = False) -> dict:
    sources = "\n\n".join(f"[{i}] {r['context']}\n{r['text']}" for i, r in enumerate(shown, 1))
    if closed_book:  # no sources were shown, so a faithfulness call would be meaningless
        f_obj, u1, e1 = None, {"prompt_tokens": 0, "completion_tokens": 0, "llm_ms": 0.0}, None
    else:
        f_obj, u1, e1 = ask_json(llm, FAITH_SYSTEM,
                                 f"SOURCES:\n\n{sources}\n\nQUESTION: {q['question']}\n\nANSWER:\n{answer_rec['answer']}")
    c_obj, u2, e2 = ask_json(llm, CORR_SYSTEM,
                             f"QUESTION: {q['question']}\n\nREFERENCE ANSWER: {reference}\n\nANSWER:\n{answer_rec['answer']}")
    claims = norm_claims(f_obj)
    corr = str((c_obj or {}).get("correctness", "")).lower()
    comp = str((c_obj or {}).get("completeness", "")).lower()
    return {
        "id": q["id"], "type": q["type"], "claims": claims,
        "correctness": corr if corr in CORRECT else None,
        "completeness": comp if comp in COMPLETE else None,
        "missing_points": (c_obj or {}).get("missing_points", []), "conflicts": (c_obj or {}).get("conflicts", []),
        "error": "; ".join(e for e in (e1, e2) if e)
                or (None if (corr in CORRECT if closed_book else claims) else "no verdict returned"),
        "usage": {k: u1[k] + u2[k] for k in u1},
    }


def summarize(recs: list[dict]) -> dict:
    live = [r for r in recs if not r["error"]]
    claims = [c for r in live for c in r["claims"]]
    cv = Counter(c["verdict"] for c in claims)
    by_type = {}
    for t in ev.TYPES:
        sel = [r for r in live if r["type"] == t]
        if sel:
            by_type[t] = {"n": len(sel), "correctness": dict(Counter(r["correctness"] for r in sel)),
                          "completeness": dict(Counter(r["completeness"] for r in sel))}
    return {
        "answers_judged": len(live), "judge_errors": len(recs) - len(live), "claims": len(claims),
        "claim_verdicts": dict(cv),
        "claim_supported_rate": (cv["supported"] / len(claims)) if claims else None,
        "supported_only_by_uncited_source": sum(1 for c in claims if c["found_in_other_source"]),
        "answers_with_contradicted_claim": sum(1 for r in live if any(c["verdict"] == "contradicted" for c in r["claims"])),
        "answers_with_not_supported_claim": sum(1 for r in live if any(c["verdict"] == "not_supported" for c in r["claims"])),
        "answers_fully_supported": sum(1 for r in live if r["claims"] and all(c["verdict"] == "supported" for c in r["claims"])),
        "correctness": dict(Counter(r["correctness"] for r in live)),
        "completeness": dict(Counter(r["completeness"] for r in live)),
        "by_type": by_type,
        "tokens": {"prompt": sum(r["usage"]["prompt_tokens"] for r in recs),
                   "completion": sum(r["usage"]["completion_tokens"] for r in recs)},
    }


# --------------------------------------------------------------------------- run
def main(name: str, ids: list, resume: bool) -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    run_path = ev.RESULTS_DIR / f"gen-{name}.json"
    out_path = ev.RESULTS_DIR / f"gen-{name}_judge.json"
    if not run_path.exists():
        raise SystemExit(f"No {run_path}")
    run = json.loads(run_path.read_text(encoding="utf-8"))
    dataset = {q["id"]: q for q in ev.load_dataset()}
    by_id = {r["chunk_id"]: r for r in ev.load_chunks()}
    chunks_md5 = hashlib.md5(ev.CHUNKS_PATH.read_bytes()).hexdigest()
    was = run["meta"].get("chunks_md5")
    if was and was != chunks_md5:
        raise SystemExit(f"chunks.jsonl changed since the run (meta {was}, now {chunks_md5}).")
    if run["meta"].get("dataset_md5") != hashlib.md5(ev.DATASET_PATH.read_bytes()).hexdigest():
        print("WARNING: dataset.jsonl differs from the one used for the run; reference answers may have changed.")
    if run["meta"]["model"] == JUDGE_MODEL:
        print(f"WARNING: judge model == generator model ({JUDGE_MODEL}): self-preference risk.")

    closed_book = run["meta"].get("mode") == "closed_book"
    todo = [q for q in run["per_question"] if q["status"] == "ok" and (not ids or q["id"] in ids)
        and not (closed_book and q["type"] == "unanswerable")]
    unknown = [i for i in ids if i not in {q["id"] for q in run["per_question"]}]
    if unknown:
        raise SystemExit(f"Unknown question id(s): {unknown}")
    for q in todo:
        miss = [c for c in q["sources_shown"] if c not in by_id]
        if miss:
            raise SystemExit(f"{q['id']}: shown chunk(s) {miss} not in chunks.jsonl (re-chunked?). Cannot judge.")

    done = {}
    if out_path.exists():
        if not resume:
            raise SystemExit(f"{out_path.name} exists. Pass --resume, or delete it (it is never mixed).")
        done = {r["id"]: r for r in json.loads(out_path.read_text(encoding="utf-8"))["per_question"]}
    todo = [q for q in todo if q["id"] not in done or done[q["id"]]["error"]]
    print(f"Judge {JUDGE_MODEL} on gen-{name}: {len(todo)} answer(s) to judge, 2 calls each.")

    llm = make_judge_llm() if todo else None
    for n, q in enumerate(todo, 1):
        shown = [by_id[c] for c in q["sources_shown"]]
        rec = judge_question(dataset[q["id"]], q, shown, dataset[q["id"]].get("reference_answer", ""), llm, closed_book)
        done[q["id"]] = rec
        cv = Counter(c["verdict"] for c in rec["claims"])
        print(f"  [{n}/{len(todo)}] {q['id']:<9} claims {len(rec['claims']):>2}  "
              f"sup {cv['supported']} nsup {cv['not_supported']} contra {cv['contradicted']}  "
              f"corr={rec['correctness']} comp={rec['completeness']}"
              + (f"  ERROR {rec['error'][:80]}" if rec["error"] else ""))
        save(out_path, name, run, chunks_md5, done)

    recs = [done[q["id"]] for q in run["per_question"] if q["id"] in done and (not ids or q["id"] in ids)]
    report(recs)
    save(out_path, name, run, chunks_md5, done)
    print(f"\nSaved {out_path}")


def save(out_path, name, run, chunks_md5, done):
    recs = list(done.values())
    meta = {"name": name, "time": datetime.now().isoformat(timespec="seconds"), "judge_model": JUDGE_MODEL,
            "generator_model": run["meta"]["model"], "judge_max_tokens": JUDGE_MAX_TOKENS,
            "prompt_md5": PROMPT_MD5, "chunks_md5": chunks_md5, "gen_run_time": run["meta"]["time"]}
    out_path.write_text(json.dumps({"meta": meta, "summary": summarize(recs), "per_question": recs},
                                   indent=2, ensure_ascii=False), encoding="utf-8")

def report(recs: list[dict], closed_book: bool = False) -> None:
    s = summarize(recs)
    print(f"\n=== judge summary ({s['answers_judged']} answers judged, {s['judge_errors']} judge errors) ===")
    if s["claims"]:
        print(f"claims {s['claims']}: {s['claim_verdicts']}   supported rate {s['claim_supported_rate']:.3f}")
        print(f"claims supported only by an UNCITED source: {s['supported_only_by_uncited_source']}")
        print(f"answers with a contradicted claim: {s['answers_with_contradicted_claim']}   "
              f"with a not_supported claim: {s['answers_with_not_supported_claim']}   "
              f"fully supported: {s['answers_fully_supported']}")
    print(f"correctness {s['correctness']}   completeness {s['completeness']}")
    for t, d in s["by_type"].items():
        print(f"  {t:<12} n={d['n']}  correctness {d['correctness']}  completeness {d['completeness']}")
    print("\nREAD THESE (contradicted and not_supported claims):")
    for r in recs:
        for c in r["claims"]:
            if c["verdict"] in ("contradicted", "not_supported", "invalid"):
                print(f"  {r['id']:<9} {c['verdict']:<13} cited {c['cited']}  {c['claim'][:150]}")
                if c["evidence"]:
                    print(f"{'':<26}evidence: {c['evidence']}")
        if r["conflicts"]:
            print(f"  {r['id']:<9} vs reference, conflicts: {r['conflicts']}")
    rows = []
    for qid, frag, want in KNOWN_CLAIMS:
        r = next((x for x in recs if x["id"] == qid and not x["error"]), None)
        if r is None:
            continue
        hits = [c for c in r["claims"] if frag in c["claim"].lower()]
        if not hits:
            rows.append((qid, frag, want, None))
        else:
            flagged = any(c["verdict"] in ("not_supported", "contradicted") for c in hits)
            rows.append((qid, frag, want, flagged))
    if rows:
        print("\nValidation against claims I checked by hand (smoke test, not an agreement statistic):")
        for qid, frag, want, got in rows:
            res = "NO MATCHING CLAIM (judge phrased it differently)" if got is None else ("MATCH" if got == want else "MISMATCH")
            print(f"  {qid:<9} {frag!r:<34} expected flagged={want!s:<5} judge flagged={got!s:<5} {res}")

if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("name", help="generation run label, e.g. g1")
    ap.add_argument("--ids", nargs="*", default=[], help="judge only these question ids")
    ap.add_argument("--resume", action="store_true", help="continue: redo judge errors and missing questions")
    a = ap.parse_args()
    main(a.name, a.ids, a.resume)