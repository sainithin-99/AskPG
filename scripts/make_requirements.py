r"""
Write requirements.txt with the EXACT versions installed in the current Python, for the packages this project
imports. Works offline (reads installed package metadata, no pip, no network).

Usage (from the repo root, cmd):
    python scripts\make_requirements.py

torch is deliberately NOT written: on your machine it is a CUDA build (2.10.0+cu128); the Dockerfile installs the
CPU build separately. The torch version found here is written as a comment so the two can be compared.
tiktoken is not listed: it is only imported (unused) by src/ingest.py, which the container never runs.
"""
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGES = ["requests", "beautifulsoup4", "transformers", "sentence-transformers", "qdrant-client", "numpy",
            "bm25s", "openai", "python-dotenv", "fastapi", "uvicorn"]


def main() -> None:
    lines, missing = [], []
    for name in PACKAGES:
        try:
            lines.append(f"{name}=={metadata.version(name)}")
        except metadata.PackageNotFoundError:
            missing.append(name)
    if missing:
        raise SystemExit(f"Not installed in this Python: {missing}. Nothing written.")
    try:
        torch_v = metadata.version("torch")
    except metadata.PackageNotFoundError:
        torch_v = "not installed"
    header = [f"# generated by scripts/make_requirements.py; local torch was {torch_v} (installed separately in the Dockerfile)"]
    out = ROOT / "requirements.txt"
    out.write_text("\n".join(header + lines) + "\n", encoding="utf-8")
    print(f"Wrote {out}")
    print("\n".join(header + lines))


if __name__ == "__main__":
    main()
